"""Fine-tune the YOLO11 plate detector on the Brazilian dataset and compare mAP.

Run after ``python -m scripts.download_dataset``::

    python -m scripts.train_detector                    # 50 epochs, imgsz 640
    python -m scripts.train_detector --epochs 100 --install

Steps
-----
1. Validate the **published** weights on the valid and test splits
   (``model.val``: precision, recall, mAP@0.5, mAP@0.5:0.95).
2. Fine-tune them with ``ultralytics`` (transfer learning: every layer is
   trained, starting from the plate detector instead of from COCO).
3. Validate the best checkpoint (chosen by Ultralytics on the *valid* split)
   with exactly the same settings and write the comparison to
   ``docs/evaluation/finetune.md`` / ``.json``.
4. ``--install`` copies the checkpoint to ``models/plate_detector_finetuned.pt``.
   The app keeps using the published weights unless the environment variable
   ``SMART_GATE_MODEL=finetuned`` is set (see ``config.py``).

Reading the numbers
-------------------
* The published model card warns that its upstream dataset has
  train/test contamination (the same source images in both splits), so the
  metrics published there are inflated. That is why the "before" column here
  is measured again on data the published model never saw.
* The "after" numbers have their own bias: the best epoch is selected on the
  valid split, and the Brazilian dataset's splits come from the same fixed
  traffic cameras (different vehicles, same scenes). The test split has only
  12 images, so its numbers move a lot with one plate.

Training choices
----------------
* ``imgsz=640``: the size the published model was trained with.
* ``fliplr=0``: a mirrored plate never appears in real life, and the
  characters would be mirrored too.
* ``patience``: stop early if mAP on the valid split stops improving.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import config  # noqa: E402
from scripts.download_dataset import DATASET_DIR, DATASET_URL, LICENSE  # noqa: E402

RUNS_DIR = config.BASE_DIR / "runs" / "detect"
REPORT_DIR = config.BASE_DIR / "docs" / "evaluation"
MODEL_CARD = "https://huggingface.co/morsetechlab/yolov11-license-plate-detection"
METRICS = ("precision", "recall", "map50", "map50_95")
EVAL_SPLITS = ("val", "test")


def box_metrics(results) -> dict[str, float]:
    """Ultralytics ``DetMetrics`` -> plain dict."""
    box = results.box
    return {"precision": float(box.mp), "recall": float(box.mr), "map50": float(box.map50),
            "map50_95": float(box.map)}


def validate(weights: Path, data: Path, imgsz: int, device: str) -> dict[str, dict[str, float]]:
    from ultralytics import YOLO

    model = YOLO(str(weights))
    return {split: box_metrics(model.val(data=str(data), split=split, imgsz=imgsz, device=device, batch=16,
                                         plots=False, verbose=False))
            for split in EVAL_SPLITS}


def comparison_markdown(before: dict, after: dict, meta: dict) -> str:
    names = {"precision": "Precision", "recall": "Recall", "map50": "mAP@0.5", "map50_95": "mAP@0.5:0.95"}
    lines = [
        "# Detector fine-tuning",
        "",
        f"Generated by `python -m scripts.train_detector` on {meta['date']}.",
        "",
        f"* Dataset: [brazilian_lpr]({DATASET_URL}) ({LICENSE}); train {meta['images']['train']}, "
        f"valid {meta['images']['valid']}, test {meta['images']['test']} images",
        f"* Base weights: published YOLO11s plate detector ([model card]({MODEL_CARD}))",
        f"* Training: {meta['epochs_run']} epochs run (max {meta['epochs']}, patience {meta['patience']}), "
        f"imgsz {meta['imgsz']}, batch {meta['batch']}, fliplr 0, device {meta['device']}, "
        f"{meta['minutes']:.1f} min",
        f"* Best checkpoint: epoch chosen by Ultralytics on the valid split (`{meta['best']}`)",
        "",
        "| Split | Metric | Published | Fine-tuned | Change |",
        "|---|---|---:|---:|---:|",
    ]
    for split in EVAL_SPLITS:
        label = "valid" if split == "val" else split
        for key in METRICS:
            b, a = before[split][key], after[split][key]
            lines.append(f"| {label} | {names[key]} | {b:.3f} | {a:.3f} | {a - b:+.3f} |")
    lines += [
        "",
        "## How to read these numbers",
        "",
        "* **Published metrics are inflated.** The model card warns that the upstream dataset has "
        "train/test contamination (the same source images in both splits), so the scores published there "
        "do not measure generalization. The *Published* column above is measured again on Brazilian "
        "images that model never saw.",
        "* **The fine-tuned numbers are optimistic too.** The best epoch is selected on the valid split, "
        "and all splits come from the same fixed traffic cameras (different vehicles, same scenes). "
        "The test split has only 12 images.",
        "* **Scenario.** 92 % of the images are motorcycles seen by a traffic camera. A gain here does not "
        "prove a gain for cars at a gate; check `scripts/evaluate.py --model <weights>` on your own images "
        "before switching models (`SMART_GATE_MODEL=finetuned`).",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", type=Path, default=DATASET_DIR / "data.yaml")
    parser.add_argument("--base", type=Path, default=config.PUBLISHED_MODEL_PATH)
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--patience", type=int, default=15)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=16)
    parser.add_argument("--workers", type=int, default=2, help="data loader processes (keep low on Windows)")
    parser.add_argument("--device", default=None, help="'0' for the first GPU, 'cpu' (default: auto)")
    parser.add_argument("--name", default="plate_finetune")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--install", action="store_true", help=f"copy best.pt to {config.FINETUNED_MODEL_PATH}")
    args = parser.parse_args()

    if not args.data.is_file():
        raise SystemExit(f"{args.data} not found. Run: python -m scripts.download_dataset")
    if not args.base.is_file():
        raise SystemExit(f"{args.base} not found. Run: python -m scripts.download_model")

    import torch
    from ultralytics import YOLO

    device = args.device or ("0" if torch.cuda.is_available() else "cpu")
    print("1/3 Validating the published weights...")
    before = validate(args.base, args.data, args.imgsz, device)

    print("2/3 Fine-tuning...")
    started = time.perf_counter()
    model = YOLO(str(args.base))
    model.train(data=str(args.data), epochs=args.epochs, patience=args.patience, imgsz=args.imgsz,
                batch=args.batch, workers=args.workers, device=device, fliplr=0.0, seed=args.seed,
                deterministic=True, project=str(RUNS_DIR), name=args.name, exist_ok=False, plots=True,
                verbose=False)
    minutes = (time.perf_counter() - started) / 60
    save_dir = Path(model.trainer.save_dir)
    best = save_dir / "weights" / "best.pt"
    epochs_run = model.trainer.epoch + 1

    print("3/3 Validating the fine-tuned weights...")
    after = validate(best, args.data, args.imgsz, device)

    manifest = json.loads((args.data.parent / "manifest.json").read_text(encoding="utf-8"))["images"]
    meta = {"date": datetime.now().strftime("%Y-%m-%d %H:%M"), "epochs": args.epochs, "epochs_run": epochs_run,
            "patience": args.patience, "imgsz": args.imgsz, "batch": args.batch, "seed": args.seed,
            "device": torch.cuda.get_device_name(0) if device != "cpu" else "CPU", "minutes": minutes,
            "best": best.relative_to(config.BASE_DIR).as_posix(),
            "images": {s: sum(e["split"] == s for e in manifest) for s in ("train", "valid", "test")}}
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / "finetune.json").write_text(json.dumps({"meta": meta, "published": before, "finetuned": after},
                                                         indent=1), encoding="utf-8")
    (REPORT_DIR / "finetune.md").write_text(comparison_markdown(before, after, meta), encoding="utf-8")
    print(comparison_markdown(before, after, meta))

    if args.install:
        config.ensure_directories()
        shutil.copyfile(best, config.FINETUNED_MODEL_PATH)
        print(f"Installed {config.FINETUNED_MODEL_PATH}. Use it with SMART_GATE_MODEL=finetuned.")


if __name__ == "__main__":
    main()
